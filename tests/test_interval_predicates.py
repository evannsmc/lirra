@pytest.mark.parametrize("system,spec", [("di", "theta_u"), ("di", "phi_plus_u"), ("x2", "theta_plus_u"),
                                         ("blimp", "phi_u"), ("blimp", "phi_plus_u")])
def test_interval_face_sets_satisfy_their_predicate_and_fit_the_workspace(system, spec):
    _, setups, _ = load_system(system, spec)
    rng = np.random.default_rng(5)
    for st in setups:
        p, T = st.problem, st.problem.terminal
        r_max = np.abs(p.C_out) @ p.tube.z_inf
        preds = {}
        for q, _ in iter_predicates(st.task.outside_formula()):
            j = int(np.argmax(np.abs(q.a[:, 0])))
            preds[(j, float(np.sign(q.a[j, 0])))] = q
        for f, face in enumerate(T.faces):
            sign = 1.0 if face.name[0] == "+" else -1.0
            j = {"x": 0, "y": 1, "z": 2}[face.name[1:]]
            q = preds[(j, sign)]
            for _ in range(50):
                x = np.zeros(p.model.n)
                for bname, poly in face.polygons.items():
                    w = rng.dirichlet(np.ones(len(poly.vertices)))
                    x[list(T.blocks[bname].states)] = w @ poly.vertices
                assert face.contains(T.blocks, x, 1e-7)
                assert float(q.lower(p.C_out @ x, r_max)) >= p.delta - 1e-9
                assert np.all(np.abs(p.C_out @ x) <= st.task.workspace - r_max + 1e-9)
                # one step of the terminal controller stays in the face set
                u = T.controller(x, f)
                assert face.contains(T.blocks, p.model.step(x, u), 1e-6)
        # waypoints inside the workspace
        assert np.all(np.abs(st.task.waypoints()) <= st.task.workspace)


