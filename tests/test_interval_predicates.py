@pytest.mark.parametrize("system,spec", [("di", "phi_u"), ("x2", "theta_plus_u"), ("blimp", "theta_u")])
def test_interval_jax_certificate_agrees_with_check(system, spec):
    import jax
    import jax.numpy as jnp

    from rl_stl.policies.segment import features, patrol_certificate

    sysm, setups, T = load_system(system, spec, "clock")
    assert T.interval and T.w_levels.shape[1] == T.p + 2
    cert = jax.jit(lambda x0, U, hy, hm, fw, lv: patrol_certificate(T, x0, U, hy, hm, fw, lv)[0],
                   static_argnums=(5,))
    rng = np.random.default_rng(7)
    n = n_ok = 0
    for trial in range(6):
        lv = trial % len(setups)
        st = setups[lv]
        p = st.problem
        x0 = sysm.random_start(rng, st)
        fw = first_enforced_window(int(rng.integers(0, 40)), p.h)
        hy = np.tile(p.C_out @ x0, (p.h - 1, 1)) + rng.normal(0, 0.05, (p.h - 1, T.p))
        hist = History(hy, [None] * (p.h - 1))
        hm = (np.arange(p.h - 1) >= fw).astype(float)
        st.nominal.reset(x0)
        Xn, Un = st.nominal.rollout(p.model, x0, p.n_plan)
        mdl = RecedingISTL(p, fw, ISTLSettings(time_limit=30))
        mdl.update(x0, hist, Xn, Un)
        res = mdl.solve()
        if not res.has_solution:
            continue
        scale = (p.u_hi - p.u_lo) / 2
        for U in (res.U, np.clip(res.U + rng.normal(0, 0.05, res.U.shape) * scale,
                                 p.u_lo + p.tube.kz[:p.n_plan], p.u_hi - p.tube.kz[:p.n_plan])):
            X = p.model.rollout(x0, U)
            ok = check_plan(p, x0, X, U, hist, None, fw).ok
            c = float(cert(jnp.asarray(x0), jnp.asarray(U), jnp.asarray(hy), jnp.asarray(hm), fw, lv))
            # MILP plans sit at the margin (delta + 1e-6); the float32 JAX rollout differs from the
            # float64 check by up to ~5e-4 there (agreement is exact with jax_enable_x64). The
            # training hinge uses eps_cert = 0.01, so require sign agreement outside a 1e-3 band.
            if abs(c) > 1e-3:
                assert ok == (c >= 0), (ok, c)
            n += 1
            n_ok += ok
        obs = features(T, x0, hy, hm, 0, lv, x_ref=Xn)
        f32 = lambda v: jnp.asarray(v, jnp.float32)
        obs_j = np.asarray(features(T, f32(x0), f32(hy), f32(hm), 0, lv, jnp, x_ref=f32(Xn)))
        assert obs.shape == (T.obs_size,) and np.allclose(obs, obs_j, atol=1e-5)
    assert n >= 4 and n_ok > 0


