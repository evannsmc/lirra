@pytest.mark.parametrize("system,spec", CASES)
def test_interval_milp_plans_satisfy_every_sampled_true_region(system, spec):
    """Every synthesized plan, with the tube, satisfies the formula with margin delta for true regions
    drawn inside the uncertainty set (exact predicates of the rotated/offset box), at the planned samples
    (interval lower bound of the true predicates over the tube box) and on concrete samples of the box."""
    sysm, setups, _ = load_system(system, spec)
    rng = np.random.default_rng(3)
    task = setups[0].task
    n_solved = 0
    for trial in range(12):  # random requests until a few are feasible
        if n_solved >= (2 if system == "x2" else 4):
            break
        lv = trial % len(setups)
        st = setups[lv]
        p = st.problem
        x0, hist, age, fw = _random_request(rng, sysm, st, task.dim)
        st.nominal.reset(x0)
        Xn, Un = st.nominal.rollout(p.model, x0, p.n_plan)
        mdl = RecedingISTL(p, fw, ISTLSettings(time_limit=30))
        mdl.update(x0, hist, Xn, Un, root_age=age)
        res = mdl.solve()
        if not res.has_solution:
            continue
        n_solved += 1
        chk = check_plan(p, x0, res.X, res.U, hist, age, fw)
        assert chk.ok, chk.reason
        off = 0 if age is None else age
        Y = res.X @ p.C_out.T
        R = np.stack([np.abs(p.C_out) @ p.tube.state(off + i) for i in range(p.n_plan + 1)])
        for _ in range(40):
            region = task.sample_true_region(rng)
            p_true = dataclasses.replace(p, psi=task.true_formula(region))
            # exact predicates of the true region with the same tube margins and history semantics
            assert interval_robustness(p_true, res.X, hist, age, fw) >= p.delta - 1e-7
            if age is None:  # concrete samples inside the tube boxes; measured history is Boolean
                Ys = Y + rng.uniform(-1, 1, Y.shape) * R
                sig = np.vstack([hist.y, Ys])
                rho = robustness(window_spec(task.true_formula(region), p.n_plan, fw), sig,
                                 observed_until=p.h - 1)
                assert rho >= p.delta - 1e-7
    assert n_solved >= 1


@pytest.mark.parametrize("system,spec", [("di", "theta_u"), ("di", "phi_plus_u"), ("x2", "phi_u"),
                                         ("blimp", "theta_plus_u")])
def test_check_agrees_with_milp_and_brute_force(system, spec):
    """The MILP solution passes the check; perturbed plans pass iff a brute-force lower bound (corner
    enumeration per predicate occurrence) and the other constraints hold; the exact-spec plan, which
    ignores the predicate uncertainty, fails the interval check on its lower bound."""
    sysm, setups, _ = load_system(system, spec)
    _, setups_exact, _ = load_system(system, PatrolTask(spec).exact_spec)
    rng = np.random.default_rng(4)
    st, st_ex = setups[1], setups_exact[1]
    p, p_ex = st.problem, st_ex.problem
    psi_nodes = [q for q, _ in iter_predicates(p.psi)]
    assert all(isinstance(q, IntervalPredicate) for q in psi_nodes)
    n_rho_fail = n_checked = 0
    for _ in range(4):
        x0 = sysm.random_start(rng, st)
        hist = History(np.tile(p.C_out @ x0, (p.h - 1, 1)), [None] * (p.h - 1))
        fw = first_enforced_window(100, p.h)
        st.nominal.reset(x0)
        Xn, Un = st.nominal.rollout(p.model, x0, p.n_plan)
        mdl = RecedingISTL(p, fw, ISTLSettings(time_limit=30))
        mdl.update(x0, hist, Xn, Un)
        res = mdl.solve()
        if not res.has_solution:
            continue
        chk = check_plan(p, x0, res.X, res.U, hist, None, fw)
        assert chk.ok, chk.reason
        assert chk.rho_lower == pytest.approx(interval_robustness(p, res.X, hist, None, fw), abs=1e-12)
        assert chk.rho_lower == pytest.approx(_brute_rho(p, res.X, hist, fw), abs=1e-9)
        scale = (p.u_hi - p.u_lo) / 2
        for sig in (0.0, 0.02, 0.05, 0.1):
            U = np.clip(res.U + sig * scale * rng.standard_normal(res.U.shape),
                        p.u_lo + p.tube.kz[:p.n_plan], p.u_hi - p.tube.kz[:p.n_plan])
            X = p.model.rollout(x0, U)
            c = check_plan(p, x0, X, U, hist, None, fw)
            brute = _brute_rho(p, X, hist, fw)
            assert c.rho_lower == pytest.approx(brute, abs=1e-9)
            assert compiled_windows(p, fw)(X, hist, None) == pytest.approx(brute, abs=1e-9)
            if brute < p.delta - 1e-6:
                assert not c.ok
                n_rho_fail += 1
            n_checked += 1
        # the exact-spec plan from the same request ignores [a], [b] (and ends in the narrower exact face
        # sets): it fails the interval check, on the lower bound whenever it hugs the nominal boundary
        st_ex.nominal.reset(x0)
        mdl_ex = RecedingISTL(p_ex, fw, ISTLSettings(time_limit=30))
        mdl_ex.update(x0, hist, Xn, Un)
        r_ex = mdl_ex.solve()
        if r_ex.has_solution:
            c_ex = check_plan(p, x0, r_ex.X, r_ex.U, hist, None, fw)
            assert not c_ex.ok
            assert c_ex.rho_lower == pytest.approx(_brute_rho(p, r_ex.X, hist, fw), abs=1e-9)
            n_rho_fail += c_ex.rho_lower < p.delta
    assert n_checked > 0 and n_rho_fail > 0


def _brute_rho(p, X, hist, fw):
    """rho_lower of the enforced windows with the predicate lower bounds from corner enumeration."""
    from stlpy.STL import LinearPredicate, STLTree

    h, Y = p.h, X @ p.C_out.T
    memo = {}

    def val(node, j):
        i = j - (h - 1)
        if i > 0:
            r = np.abs(p.C_out) @ p.tube.state(i)
            return _corner_min(node.a_lo, node.a_hi, node.b_hi, Y[i], r)
        y = Y[0] if i == 0 else hist.y[j]
        return np.inf if _corner_min(node.a_lo, node.a_hi, node.b_hi, y, np.zeros(len(y))) >= 0 else -np.inf

    def rec(node, j):
        key = (id(node), j)
        if key not in memo:
            if isinstance(node, LinearPredicate):
                memo[key] = val(node, j)
            else:
                assert isinstance(node, STLTree)
                vs = [rec(c, j + dt) for c, dt in zip(node.subformula_list, node.timesteps)]
                memo[key] = min(vs) if node.combination_type == "and" else max(vs)
        return memo[key]

    return min(rec(p.psi, s) for s in range(fw, p.n_plan))


