def test_delay_compensated_interval_requests_stay_feasible():
    """Always-on loop with delay compensation: every request's warm start (the shifted cached plan) passes
    the check, so the MILP must be feasible; cached-plan samples sitting on the planning margin must not
    flip their fixed binaries through rounding of the recomputed lower endpoint."""
    from rl_stl.evaluation.systems import run_episode
    from rl_stl.supervisor.receding import RecedingConfig, RecedingSupervisor

    system, setups, T = load_system("di", "phi_u", "clock")
    st = system.build(0)
    x0 = system.eval_start(np.random.default_rng(12345), setups[0])
    sup = RecedingSupervisor(st.problem, st.K, st.nominal, None,
                             RecedingConfig(variant="always_on", latency_steps=2, reference="clock"),
                             ISTLSettings(time_limit=10.0))
    ep = run_episode(system, st, sup, x0, 30.0, 0)
    rt = [s for s in ep["solves"] if s["request_step"] >= 0]
    assert rt and all(s["warm_start_feasible"] for s in rt)
    assert all(s["status"] in ("optimal", "suboptimal") for s in rt), [s["status"] for s in rt]
    assert np.all(ep["rho_windows"] >= 0)
